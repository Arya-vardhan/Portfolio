/* ==================== WEB AUDIO API SOUND SYSTEM ==================== */

let audioCtx = null;
let audioEnabled = true;

export function initAudio() {
  if (!audioCtx) {
    audioCtx = new (window.AudioContext || window.webkitAudioContext)();
  }
  if (audioCtx.state === 'suspended') {
    audioCtx.resume();
  }
}

export function isAudioEnabled() {
  return audioEnabled;
}

export function toggleAudio() {
  audioEnabled = !audioEnabled;
  const label = document.getElementById('audio-label');
  const icon = document.getElementById('audio-icon-on');
  if (label) label.textContent = audioEnabled ? 'FX: ON' : 'FX: OFF';
  if (icon) {
    icon.classList.toggle('text-amber-500', audioEnabled);
    icon.classList.toggle('text-stone-500', !audioEnabled);
  }
  if (audioEnabled) playCameraSwoosh();
  return audioEnabled;
}

export function playCameraSwoosh() {
  if (!audioEnabled) return;
  initAudio();
  try {
    const osc = audioCtx.createOscillator();
    const gain = audioCtx.createGain();
    osc.type = 'sine';
    osc.frequency.setValueAtTime(140, audioCtx.currentTime);
    osc.frequency.exponentialRampToValueAtTime(70, audioCtx.currentTime + 0.22);
    gain.gain.setValueAtTime(0.08, audioCtx.currentTime);
    gain.gain.exponentialRampToValueAtTime(0.001, audioCtx.currentTime + 0.25);
    osc.connect(gain);
    gain.connect(audioCtx.destination);
    osc.start();
    osc.stop(audioCtx.currentTime + 0.25);
  } catch (e) {}
}

